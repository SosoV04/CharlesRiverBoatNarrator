// Percentage-based coordinates (0–100) for each numbered circle on the tour map.
// Positions are relative to the map image's dimensions, so they remain correct
// at any display size as long as the map keeps its aspect ratio.
//
// SOURCE MAP
//   File:         map.png at repo root  (redrawn artwork, 2026-08-08)
//   Dimensions:   1498 × 1050 (landscape, aspect 1.427)
//   Marker style: mint circles ~rgb(165,243,133), ~25px radius, black numbers 1–45
//
// EXTRACTION METHOD
//   Generated by scripts/extract-map-coords.mjs — do not hand-edit. The script
//   decodes map.png with no image dependencies, masks the mint marker fill
//   (G>225, R<205, G>R+50, G>B+70), groups masked pixels into 4-way connected
//   components, and keeps those that are marker-shaped (area 700–2600px,
//   bounding box 36–62px per side, near-square). That yields exactly 45
//   components; their centroids become the percentages below.
//
//   Centroid detection finds WHERE each circle is but not WHICH number is
//   printed in it. The number for each was read by eye from a 6× enlarged
//   crop montage (`--crops`) and recorded in the script's DIGIT_ORDER.
//
// VERIFICATION (what was actually checked against the redrawn map, 2026-08-08)
//   - 45 entries, keys 1–45, no gaps, no duplicates, all percentages in 0–100.
//   - Digit reading is a bijection over 1–45 — every number used exactly once.
//   - Every coordinate re-projected to pixels lands on a detected circle
//     centroid: 45/45, worst error 0.09px.
//   - Each detected circle is claimed by exactly one number: no collisions,
//     none unclaimed.
//   - `--verify` montage read by eye: the 45 crops, ordered by map number,
//     read 1, 2, 3 … 45 in sequence.
//
// SCHEMA
//   COORDS[mapNumber] = { x_pct, y_pct }
//     mapNumber  Integer 1–45, matching `mapNumber` in narration/stops.js.
//     x_pct      Horizontal position, 0 = left edge, 100 = right edge.
//     y_pct      Vertical position,   0 = top edge,  100 = bottom edge.
//
// USAGE (map button rendering, sketch)
//   for (const [num, { x_pct, y_pct }] of Object.entries(COORDS)) {
//     const btn = document.createElement("a");
//     btn.href = `#stop-${num}`;
//     btn.textContent = num;
//     btn.style.cssText = `left:${x_pct}%; top:${y_pct}%; transform:translate(-50%,-50%)`;
//     mapContainer.appendChild(btn);
//   }
//   The parent element should be `position:relative` and match the map's
//   aspect ratio; buttons are `position:absolute`.
//
//   The tightest pair is 17 and 18, 57px apart centre to centre on the source
//   image, against a ~50px printed circle. So a button drawn at circle size
//   clears its neighbours — unlike the previous artwork, where 25 and 31 sat
//   closer together than one button was wide.
//
// REGENERATION
//   See data/README.md. Short version: re-run the extraction script rather than
//   editing this file by hand.
// -----------------------------------------------------------------------------

